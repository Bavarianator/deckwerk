/// Gebündelte Schrift. Office-Schriften messen über metrikgleiche Zwillinge (Arial→Arimo, Calibri→Carlito, Georgia→Gelasio).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FontDef {
    pub css: &'static str,
    pub pptx: &'static str,
    pub embed: Option<&'static str>,
    pub serif: bool,
    pub single: bool,
}

impl FontDef {
    pub fn to_ref(self) -> FontRef {
        FontRef {
            css: self.css.into(),
            pptx: self.pptx.into(),
            embed: self.embed.map(Into::into),
            serif: self.serif,
            single: self.single,
            files: None,
            fallback: None,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FontCat {
    Grotesk,
    Humanist,
    Geometric,
    Condensed,
    Serif,
    DisplaySerif,
    Slab,
    Mono,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FontRole {
    Head,
    Body,
    Both,
}

/// slop = Standard generierter Designs, nur auf Wunsch; common = überall zu sehen.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FontFlag {
    Slop,
    Common,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum License {
    Ofl,
    Apache,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FontInfo {
    pub family: &'static str,
    pub cat: FontCat,
    pub mood: &'static str,
    pub role: FontRole,
    pub weights: &'static [u16],
    pub italic: bool,
    pub flag: Option<FontFlag>,
    pub pairs: &'static [&'static str],
    pub fallback: &'static str,
    pub license: License,
    pub office: bool,
}

impl FontCat {
    /// serif/slab (fontRef: `/serif|slab/.test(cat)`)
    pub fn serif(self) -> bool {
        matches!(self, FontCat::Serif | FontCat::DisplaySerif | FontCat::Slab)
    }
}

/// Gebündelte Schrift nach exaktem Namen (FONTS[name]).
pub fn font(name: &str) -> Option<FontDef> {
    FONT_LIST.iter().find(|(n, _)| *n == name).map(|(_, f)| *f)
}

/// fontInfo: Katalogeintrag, Groß/klein und Rand egal.
pub fn font_info(name: &str) -> Option<&'static FontInfo> {
    let n = name.trim().to_lowercase();
    FONT_CATALOG.iter().find(|i| i.family.to_lowercase() == n)
}

/// items.ts knownFont: gebündelt oder exakt so im Katalog.
pub fn known_font(name: &str) -> bool {
    font(name).is_some() || font_info(name).is_some_and(|i| i.family == name)
}

/// Zwischengewichte sind eigene Familien („Inter SemiBold“); 400 und 700 gehören zur Familie selbst.
pub fn instance_family(family: &str, weight: u16) -> String {
    let n = match weight {
        100 => "Thin",
        200 => "ExtraLight",
        300 => "Light",
        500 => "Medium",
        600 => "SemiBold",
        800 => "ExtraBold",
        900 => "Black",
        _ => return family.into(),
    };
    format!("{family} {n}")
}

/// Nächstes verfügbares Gewicht, bei Gleichstand das schwerere.
pub fn nearest_weight(info: &FontInfo, weight: u16) -> u16 {
    let d = |w: u16| (w as i32 - weight as i32).abs();
    info.weights.iter().fold(info.weights[0], |best, &w| {
        if d(w) < d(best) || (d(w) == d(best) && w > best) {
            w
        } else {
            best
        }
    })
}

/// „meintest du …?“: Levenshtein auf Kleinbuchstaben ohne Leerzeichen.
pub fn suggest_font(name: &str) -> Option<&'static str> {
    let norm = |s: &str| {
        s.to_lowercase()
            .chars()
            .filter(|c| !c.is_whitespace())
            .collect::<Vec<_>>()
    };
    let a = norm(name);
    let dist = |b: &[char]| {
        let mut d: Vec<usize> = (0..=b.len()).collect();
        for i in 1..=a.len() {
            let mut prev = d[0];
            d[0] = i;
            for j in 1..=b.len() {
                let t = d[j];
                d[j] = (d[j] + 1)
                    .min(d[j - 1] + 1)
                    .min(prev + usize::from(a[i - 1] != b[j - 1]));
                prev = t;
            }
        }
        d[b.len()]
    };
    // min_by_key nimmt bei Gleichstand den ersten, wie die stabile Sortierung in TS
    let (fam, d) = FONT_CATALOG
        .iter()
        .map(|i| (i.family, dist(&norm(i.family))))
        .min_by_key(|x| x.1)?;
    (d <= 2.max(a.len() / 3)).then_some(fam)
}

/// fontRef: gebündelt, Katalogschrift mit geladenen Dateien oder deren gebündelter Ersatz.
pub fn font_ref(
    name: Option<&str>,
    files: Option<&BTreeMap<String, FontFiles>>,
) -> Option<FontRef> {
    let name = name.filter(|n| !n.is_empty())?;
    if let Some(f) = font(name) {
        return Some(f.to_ref());
    }
    let info = font_info(name)?;
    let alt = font(info.fallback)?;
    match files
        .and_then(|f| f.get(info.family))
        .filter(|f| !f.regular.is_empty())
    {
        Some(fl) => Some(FontRef {
            css: info.family.into(),
            pptx: info.family.into(),
            embed: None,
            serif: info.cat.serif(),
            single: fl.bold.is_none(),
            files: Some(fl.clone()),
            fallback: Some(alt.css.into()),
        }),
        None => Some(alt.to_ref()),
    }
}

