/// winOfTtf: Win-Höhe einer TTF in em; None bei kaputter Datei, fehlender Tabelle oder Summe 0.
pub fn win_of_ttf(b: &[u8]) -> Option<f64> {
    let u16_at = |o: usize| Some(u16::from_be_bytes(b.get(o..o + 2)?.try_into().ok()?));
    let u32_at = |o: usize| Some(u32::from_be_bytes(b.get(o..o + 4)?.try_into().ok()?) as usize);
    let table = |tag: &[u8]| {
        (0..u16_at(4)? as usize).find_map(|i| {
            (b.get(12 + i * 16..16 + i * 16)? == tag)
                .then(|| u32_at(20 + i * 16))
                .flatten()
        })
    };
    let (os, head) = (table(b"OS/2")?, table(b"head")?);
    let win = u16_at(os + 74)? as u32 + u16_at(os + 76)? as u32;
    let upem = u16_at(head + 18)?;
    (win > 0 && upem > 0).then(|| win as f64 / upem as f64)
}

