pub fn layout_name(id: &str) -> &str {
    LAYOUT_NAMES.iter().find(|l| l.0 == id).map_or(id, |l| l.1)
}

pub fn field_name(key: &str) -> &str {
    FIELD_NAMES.iter().find(|f| f.0 == key).map_or(key, |f| f.1)
}
